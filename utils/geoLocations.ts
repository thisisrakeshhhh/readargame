export function searchLocations(query: string): GeoLocation[] {
  if (!query || query.trim() === '') {
    return WORLD_LOCATIONS.slice(0, 10);
  }

  const q = query.toLowerCase().trim();

  return WORLD_LOCATIONS.filter((loc) => {
    return (
      loc.name.toLowerCase().includes(q) ||
      loc.country.toLowerCase().includes(q) ||
      loc.region.toLowerCase().includes(q) ||
      loc.theaterType.toLowerCase().includes(q) ||
      loc.countryCode.toLowerCase() === q
    );
  });
}

export function findNearestLocation(lat: number, lng: number): GeoLocation {
  let nearest = WORLD_LOCATIONS[0];
  let minDistance = Infinity;

  WORLD_LOCATIONS.forEach((loc) => {
    const dLat = loc.lat - lat;
    const dLng = loc.lng - lng;
    const dist = Math.sqrt(dLat * dLat + dLng * dLng);
    if (dist < minDistance) {
      minDistance = dist;
      nearest = loc;
    }
  });

  return nearest;
}
